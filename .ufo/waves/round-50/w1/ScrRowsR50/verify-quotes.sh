#!/usr/bin/env bash
# verify-quotes.sh — round 50 seat ScrRowsR50.
# Checks every admit line in gate.md against the round-50 pins: the quote is a literal
# substring of the cited pin at the cited line, the quote and pin:line and URL appear
# verbatim in gate.md, the line carries "opened 2026-10-27", and the word count is <=25
# and equals the stated count. Also re-checks the 14 upstream pins byte-for-byte against
# round-49's pins and counts the admit and reject lines. Read-only.
# Run: bash .ufo/waves/round-50/w1/ScrRowsR50/verify-quotes.sh
set -u
SEAT=$(cd -- "$(dirname -- "$0")" && pwd)
LANE=$(cd -- "$SEAT/../../../../.." && pwd)
PIN="$LANE/.ufo/waves/round-50/fetch"
OLD="$LANE/.ufo/waves/round-49/fetch"
GATE="$SEAT/gate.md"
[ -d "$PIN" ] || { echo "ERROR: pin dir missing: $PIN" >&2; exit 2; }
[ -f "$GATE" ] || { echo "ERROR: gate.md missing: $GATE" >&2; exit 2; }
fail=0; n=0

DATA=$(cat <<'EOF'
S352	Hyprland-KeybindManager.cpp	369	5	pKeyboard->m_resolveBindsBySym ? pKeyboard->m_xkbSymState : m_xkbTranslationState	https://raw.githubusercontent.com/hyprwm/Hyprland/efb50993780079460b0cbed1363e2166a2de1d9f/src/managers/KeybindManager.cpp
S353	Hyprland-legacy-ConfigManager.cpp	1484	3	key.starts_with("code:") && isNumber(key.substr(5))	https://raw.githubusercontent.com/hyprwm/Hyprland/efb50993780079460b0cbed1363e2166a2de1d9f/src/config/legacy/ConfigManager.cpp
S354	Hyprland-InputManager.cpp	1711	13	m_lastMods         = MODS.depressed; // for hyprland keybinds use; not for sending to seat	https://raw.githubusercontent.com/hyprwm/Hyprland/efb50993780079460b0cbed1363e2166a2de1d9f/src/managers/input/InputManager.cpp
S355	xkbcommon-keysym.c	268	9	The "best" case-insensitive match is the lower-case keysym name.	https://raw.githubusercontent.com/xkbcommon/libxkbcommon/xkbcommon-1.13.2/src/keysym.c
S356	xkbcommon-ks_tables.h	3	10	This file comes from libxkbcommon and was generated by update-keysyms-names-handling.py	https://raw.githubusercontent.com/xkbcommon/libxkbcommon/xkbcommon-1.13.2/src/ks_tables.h
S357	xkbcommon-tools-how-to-type.c	101	7	Treat the argument only as a keysym	https://raw.githubusercontent.com/xkbcommon/libxkbcommon/xkbcommon-1.13.2/tools/how-to-type.c
S358	xkbcommon-xkbcommon-keysyms.h	471	4	non-deprecated alias for dead_tilde	https://raw.githubusercontent.com/xkbcommon/libxkbcommon/xkbcommon-1.13.2/include/xkbcommon/xkbcommon-keysyms.h
S359	wiki-Binds.md	40	10	The name you should use is the segment after `XKB_KEY_`.	https://raw.githubusercontent.com/hyprwm/hyprland-wiki/d5f07c60e16fe03744aabb76e492117b7f7c4679/content/Configuring/Basics/Binds.md
S360	wiki-Variables.md	219	12	keybinds will always act as if the first specified layout is active	https://raw.githubusercontent.com/hyprwm/hyprland-wiki/d5f07c60e16fe03744aabb76e492117b7f7c4679/content/Configuring/Basics/Variables.md
S361	binds-live-r50.txt	9	6	binds=192 named=142 code=42 mouse=6 switch=2 catch_all=0	.ufo/waves/round-50/fetch/binds-live-r50.txt
S362	xkbcommon-state.c	116	6	return (entry) ? entry->level : 0;	https://raw.githubusercontent.com/xkbcommon/libxkbcommon/xkbcommon-1.13.2/src/state.c
S363	Hyprland-IKeyboard.hpp	14	5	HL_MODIFIER_SHIFT = (1 << 0),	https://raw.githubusercontent.com/hyprwm/Hyprland/efb50993780079460b0cbed1363e2166a2de1d9f/src/devices/IKeyboard.hpp
EOF
)

while IFS=$'\t' read -r id file line words quote url; do
  [ -n "${id:-}" ] || continue
  n=$((n+1)); bad=""
  # 1. quote at the cited line of the pin
  if sed -n "${line}p" "$PIN/$file" | grep -qF -- "$quote"; then :; else bad="$bad line-mismatch"; fi
  # 2. quote verbatim in gate.md
  grep -qF -- "$quote" "$GATE" || bad="$bad quote-not-in-gate"
  # 3. pin:line token in gate.md
  grep -qF -- ".ufo/waves/round-50/fetch/$file:$line" "$GATE" || bad="$bad pintoken-missing"
  # 4. URL (or own-work source path) in gate.md
  grep -qF -- "$url" "$GATE" || bad="$bad url-missing"
  # 5. the admit line itself carries the id and the access date
  aline=$(grep -F -- "- **$id admit**" "$GATE" || true)
  [ -n "$aline" ] || bad="$bad admit-line-missing"
  printf '%s\n' "$aline" | grep -qF -- "opened 2026-10-27" || bad="$bad date-missing"
  # 6. word count <=25 and equal to the stated count
  wc_actual=$(printf '%s' "$quote" | wc -w)
  [ "$wc_actual" = "$words" ] || bad="$bad wordcount $wc_actual!=$words"
  [ "$wc_actual" -le 25 ] || bad="$bad over-25"
  if [ -z "$bad" ]; then
    printf 'PASS %s %s:%s (%s words) %s\n' "$id" "$file" "$line" "$words" "$quote"
  else
    printf 'FAIL %s %s:%s%s\n' "$id" "$file" "$line" "$bad"; fail=$((fail+1))
  fi
done <<< "$DATA"

# pins byte-equal to round 49
eq=0; tot=0
for f in Hyprland-KeybindManager.cpp Hyprland-legacy-ConfigManager.cpp Hyprland-InputManager.cpp Hyprland-IKeyboard.hpp Hyprland-IKeyboard.cpp Hyprland-ConfigValues.cpp xkbcommon-keysym.c xkbcommon-keysym.h xkbcommon-ks_tables.h xkbcommon-tools-how-to-type.c xkbcommon-xkbcommon-keysyms.h xkbcommon-state.c wiki-Binds.md wiki-Variables.md; do
  tot=$((tot+1))
  if cmp -s "$PIN/$f" "$OLD/$f"; then eq=$((eq+1)); else echo "FAIL pin differs from round 49: $f"; fail=$((fail+1)); fi
done
printf 'PASS pins byte-equal to round-49: %d/%d\n' "$eq" "$tot"

[ "$n" = 12 ] && printf 'PASS admit lines: %d/12 (each with URL, opened 2026-10-27, pin:line, quote, word count)\n' "$n" \
  || { printf 'FAIL admit lines: %d/12\n' "$n"; fail=$((fail+1)); }
rej=$(grep -c -e '^- \*\*REJECT' "$GATE" || true)
[ "$rej" = 5 ] && printf 'PASS reject lines: %d/5 present\n' "$rej" \
  || { printf 'FAIL reject lines: %d/5\n' "$rej"; fail=$((fail+1)); }

if [ "$fail" -eq 0 ]; then echo '---'; echo 'ALL QUOTES VERIFIED'; exit 0; fi
echo '---'; echo "FAILED: $fail"; exit 1
