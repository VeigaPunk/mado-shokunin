def block(path, a, b, rel=None):
    lines = open(path, encoding="utf-8", errors="replace").read().split("\n")
    raw = "\n".join(lines[a - 1:min(b, len(lines))])
    body = "\n".join("%d:%s" % (n, lines[n - 1]) for n in range(a, min(b, len(lines)) + 1))
    name = rel or os.path.basename(path)
    return "== %s:%d-%d ==\n%s\n" % (name, a, b, body), raw


def norm(s):
    return re.sub(r"\s+", " ", s).strip()


