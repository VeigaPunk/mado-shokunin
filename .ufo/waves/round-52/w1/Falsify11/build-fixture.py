#!/usr/bin/env python3
"""Seat-local fixture builder: write a no-work ledger into a scratch clone.

Mode `padded`: 82 production-grammar rows generated from the population at --rev, each
with a generic description and a SELF pointer at quality/tool-ledger.md.
Mode `norm`: the committed control with its 4-cell rows rewritten to 3 cells and its
pointer left as a bare, non-backticked path (commentary suffix preserved).

Writes only inside the clone whose toplevel is asserted.
"""
import argparse
import os
import re
import subprocess
import sys

QUALITY_PY = re.compile(r"^quality/[^/]+\.py$")
COUNTERS_PY = re.compile(r"^quality/counters/[^/]+\.py$")


def git(repo, *args):
    env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"),
           "HOME": os.environ.get("HOME", "/nonexistent"),
           "GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": os.devnull, "LC_ALL": "C"}
    p = subprocess.run(["git", "-C", repo] + list(args), capture_output=True, env=env)
    if p.returncode != 0:
        raise SystemExit("git failed: %s" % p.stderr.decode("utf-8", "replace"))
    return p.stdout


def population(repo, rev):
    out = git(repo, "ls-tree", "-r", "-z", rev)
    paths = []
    for rec in out.split(b"\0"):
        if not rec:
            continue
        head, sep, path = rec.partition(b"\t")
        if not sep:
            continue
        f = head.split()
        if len(f) < 3 or f[1] != b"blob":
            continue
        p = path.decode("utf-8", "surrogateescape")
        if p.startswith("tools/") or QUALITY_PY.match(p) or COUNTERS_PY.match(p):
            paths.append(p)
    return sorted(set(paths))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--rev", required=True)
    ap.add_argument("--mode", choices=("padded", "norm", "norm-one"), required=True)
    ap.add_argument("--control", required=True)
    a = ap.parse_args()
    top = git(a.repo, "rev-parse", "--show-toplevel").decode().strip()
    if os.path.realpath(top) != os.path.realpath(a.repo):
        raise SystemExit("refusing: toplevel %r != repo %r" % (top, a.repo))
    out = ["# no-work ledger fixture (%s) — generated by seat Falsify11" % a.mode,
           "", "| instrument | description | accountability pointer |", "|---|---|---|"]
    if a.mode == "padded":
        for p in population(a.repo, a.rev):
            out.append("| `%s` | Accountability pointer for this instrument; reads nothing, "
                        "writes nothing, commentary only. | `quality/tool-ledger.md` |" % p)
    else:
        # Control columns are Tool | Reads | Writes | Owner. The self-pointer lives in the
        # Reads cell and the generic text in the Owner cell; map them onto ledger grammar.
        seen_header = False
        with open(a.control, encoding="utf-8") as fh:
            for line in fh:
                s = line.strip()
                if not s.startswith("|"):
                    continue
                cells = [c.strip() for c in s.strip("|").split("|")]
                if len(cells) != 4:
                    continue
                if not seen_header:
                    seen_header = True
                    continue
                if all(re.fullmatch(r":?-{3,}:?", c) for c in cells if c):
                    continue

                m = re.search(r"[A-Za-z0-9._-]+(?:/[A-Za-z0-9._#-]+)+", cells[1])
                pointer = m.group(0) if m else cells[1]
                row = "| `%s` | %s | `%s` |" % (cells[0], cells[3], pointer)
                if a.mode == "norm-one" and row in out:
                    continue
                out.append(row)
    path = os.path.join(a.repo, "quality", "tool-ledger.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
