#!/usr/bin/env bash
# verify-quotes.sh — greps each gate quote at its computed locator in the pinned bytes.
set -u
cd "$(dirname "$0")/pins" || exit 2
fail=0
check() { # file line quote
  local f=$1 l=$2 q=$3 got
  got=$(sed -n "${l}p" "$f")
  if printf '%s' "$got" | grep -qF -- "$q"; then
    printf 'PASS %s:%s %s\n' "$f" "$l" "$q"
  else
    printf 'FAIL %s:%s %s\n     got: %s\n' "$f" "$l" "$q" "$got"; fail=1
  fi
}
check Hyprland-KeybindManager.cpp 369 'pKeyboard->m_resolveBindsBySym ? pKeyboard->m_xkbSymState : m_xkbTranslationState'
check Hyprland-KeybindManager.cpp 652 'modmask != k->modmask && !k->ignoreMods'
check Hyprland-legacy-ConfigManager.cpp 1484 'key.starts_with("code:") && isNumber(key.substr(5))'
check Hyprland-legacy-ConfigManager.cpp 1525 "case 'i': ignoreMods = true; break;"
check Hyprland-InputManager.cpp 1224 'getDeviceInt(devname, "resolve_binds_by_sym", "input:resolve_binds_by_sym")'
check Hyprland-InputManager.cpp 1711 'm_lastMods         = MODS.depressed; // for hyprland keybinds use; not for sending to seat'
check xkbcommon-keysym.h 45 '#define XKB_KEYSYM_UNICODE_MIN    0x01000100'
check xkbcommon-keysym.c 268 'The "best" case-insensitive match is the lower-case keysym name.'
check xkbcommon-ks_tables.h 3 'This file comes from libxkbcommon and was generated by update-keysyms-names-handling.py'
check xkbcommon-tools-how-to-type.c 101 'Treat the argument only as a keysym'
check xkbcommon-tools-how-to-type.c 626 'printf("=== Direct access ===\n\n");'
check xkbcommon-xkbcommon-keysyms.h 471 'non-deprecated alias for dead_tilde'
check wiki-Binds.md 40 'The name you should use is the segment after `XKB_KEY_`.'
check wiki-Binds.md 469 'resolve_binds_by_sym = 1'
check xkbcommon-state.c 116 'return (entry) ? entry->level : 0;'
check xkbcommon-state.c 91 'type->entries[i].mods.mask == mods)'
check Hyprland-IKeyboard.hpp 14 'HL_MODIFIER_SHIFT = (1 << 0),'
check Hyprland-IKeyboard.hpp 124 'm_resolveBindsBySym = false;'
check wiki-Variables.md 219 'keybinds will always act as if the first specified layout is active'
echo "---"
[ "$fail" -eq 0 ] && echo "ALL QUOTES VERIFIED" || echo "QUOTE VERIFICATION FAILED"
exit "$fail"
