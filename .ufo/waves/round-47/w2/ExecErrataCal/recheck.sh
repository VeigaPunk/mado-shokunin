REV=$(git rev-parse HEAD)
STAMP=$(git log -1 --format=%cI "$REV")

begin() {
  local name=$1
  { printf '# receipt %s.txt — lane %s\n# rev=%s (%s)\n# generated by recheck.sh, ExecErrataCal round 47 w2\n' \
      "$name" "$LANE" "$REV" "$STAMP"; } > "$OUT/$name.txt"
}

run() {
  local name=$1; shift
  local cmd="$*"
  { printf '\n$ %s\n' "$cmd"; } >> "$OUT/$name.txt"
  timeout 180 bash -c "$cmd" >> "$OUT/$name.txt" 2>&1
  local rc=$?
  printf '[rc=%d]\n' "$rc" >> "$OUT/$name.txt"
}

