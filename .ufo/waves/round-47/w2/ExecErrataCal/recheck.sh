#!/usr/bin/env bash
# recheck.sh — ExecErrataCal, round 47 w2 (R4c).
# Re-runs every truth command of .ufo/waves/round-47/w1/ScrErrataCal/errata.md over committed
# bytes of the lane at HEAD, and prints command + output + exit code per block into receipts/.
# Read-only: git read verbs and text greps only. Nothing in the lane outside this seat is written.
