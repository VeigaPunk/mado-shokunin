#!/usr/bin/env python3
"""Classify every finding of quality/check-session-material.py at 4d22eeb.

Input: the gate's own output (receipts/01-baseline.txt, 97 FINDING lines).
Output: triage.tsv (one line per finding) and the per-class counts on stdout.

Classes are assigned from provenance evidence gathered by opening each file at
the scanned revision:

  REAL       content captured from this host's live session by a command
             (ss socket table, bare /home paths from the host tree, client
             dumps of the host compositor).
  SYNTHETIC  content fabricated or generated by a seat's own code: fixture
             files, counter selftest constants, probe-client dumps from a
             nested sandbox compositor, lesson demo files, the gate's own
             selftest constants.
  FP         the pattern matched text that is not session material at all.

No value of real material (title, program, pid, serial, home path) is copied
into the table: the basis column names the mechanism only.
"""

import collections
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SEAT = os.path.dirname(HERE)
BASELINE = os.path.join(SEAT, "receipts", "01-baseline.txt")
OUT = os.path.join(SEAT, "triage.tsv")

REAL = {
    ".ufo/waves/round-35/scratch-evidence/SentProvenance/S203.scope.txt":
        "host tree: bare /home paths from a grep receipt of the host install dir",
    ".ufo/waves/round-37/receipts/eventq-live-ss.txt":
        "live ss socket table captured on this host (host program names + pids)",
    ".ufo/waves/round-37/res/reports/L1Mado37-2.CritEntryE2.md":
        "report quoting the live host ss rows (socket path placeheld, pid/program/fd kept)",
    ".ufo/waves/round-37/w1/reports/ExecEventqB.md":
        "report quoting a live host ss row",
    ".ufo/waves/round-37/w1/reports/ExecProcCrosscheck.md":
        "report quoting live host ss rows",
    ".ufo/waves/round-37/w1/reports/RevC2Code.md":
        "report quoting live host ss rows",
    ".ufo/waves/round-37/w1/reports/ScoutRollingLog.md":
        "report quoting live host ss rows",
    ".ufo/waves/round-37/w1/reports/ScoutSsSemantics.md":
        "report quoting the live host ss table",
    ".ufo/waves/round-37/w1/scratch/ExecEventqA/live-ss.txt":
        "live ss socket table captured on this host",
    ".ufo/waves/round-38/receipts/eventq-live-ss.txt":
        "live ss socket table captured on this host (whole host process table)",
    ".ufo/waves/round-38/w1/reports/RevC2v3.md":
        "report quoting a live host ss row",
    ".ufo/waves/round-38/w1/reports/RevLiveTriplet.md":
        "report quoting live host ss rows",
    ".ufo/waves/round-38/w1/reports/ScoutR29Refusal.md":
        "report quoting a live host ss row",
    ".ufo/waves/round-39/w1/ExecEventqSnapshot/eventq-live-census.txt":
        "live ss socket table captured on this host",
    ".ufo/waves/round-43/w1/ExecLiveHost/live-census.txt":
        "host census: bare /home paths from the host tree",
}

SYNTHETIC = [
    (re.compile(r"^\.ufo/waves/round-43/w1/ExecOracleGkeep/"),
     "sandbox oracle dump: seat's own probe client in a nested headless "
     "Hyprland, title gkeep-oracle-probe (74/74 title values)"),
    (re.compile(r"^\.ufo/waves/round-44/w1/ScrLessonSkeleton/c1-demo/"),
     "lesson demo fixture: address 0x1, fabricated class/title"),
    (re.compile(r"^\.ufo/waves/round-45/w1/ExecPrivacyGate/check-session-material\.py$"),
     "gate's own selftest constants (blob byte-identical to "
     "quality/check-session-material.py at the same revision)"),
    (re.compile(r"^\.ufo/waves/round-45/w1/RevengerOmarchy/fixtures/"),
     "round-45 fixture dump: fabricated identity (Fake Corp / SN00000)"),
    (re.compile(r"^\.ufo/waves/round-45/w1/ScrMistakes/mutants\.sh$"),
     "mutant driver written into a scratch git repo: title REDACTED"),
    (re.compile(r"^\.ufo/waves/round-37/w1/scratch/CritC2Cheap/handsnap\.txt$"),
     "hand-built socket rows: placeheld socket path, pid 1"),
    (re.compile(r"^\.ufo/waves/round-37/w1/scratch/SimplifyCounters/diff_c2\.sh$"),
     "mutant driver: hand-built row, socket /x, pid 1"),
    (re.compile(r"^\.ufo/waves/round-37/w1/scratch/(CritAxisClaim/controls_critaxis|"
                r"ExecEventqB/setup-reasons|SimplifyCounters/)"),
     "counter fixture constants: placeheld socket path, but the host Hyprland pid "
     "and a live client pid are reused (redaction gap, see report)"),
]

CLASSES = ("REAL", "SYNTHETIC", "FP")


def classify(path):
    if path in REAL:
        return "REAL", REAL[path]
    for pattern, basis in SYNTHETIC:
        if pattern.search(path):
            return "SYNTHETIC", basis
    return "FP", "unclassified"


def main():
    rows = []
    with open(BASELINE, encoding="utf-8") as handle:
        for line in handle:
            if not line.startswith("FINDING "):
                continue
            match = re.search(r"file=(\S+) rule=(\S+) count=(\d+)", line)
            if not match:
                continue
            path, rule, count = match.group(1), match.group(2), int(match.group(3))
            cls, basis = classify(path)
            rows.append((path, rule, count, cls, basis))
    if not rows:
        sys.exit("no FINDING lines in %s" % BASELINE)

    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write("path\trule\tcount\tclass\tbasis\n")
        for row in sorted(rows):
            handle.write("\t".join(str(field) for field in row) + "\n")

    tally = collections.Counter(row[3] for row in rows)
    per_rule = collections.Counter((row[3], row[1]) for row in rows)
    print("findings=%d" % len(rows))
    for cls in CLASSES:
        print("%s=%d" % (cls, tally[cls]))
    for cls in CLASSES:
        for rule in ("R1_CLIENT_DUMP", "R2_PROC_TABLE", "R3_MONITOR_IDENT",
                     "R4_HOME_LISTING"):
            if per_rule[(cls, rule)]:
                print("%s %s=%d" % (cls, rule, per_rule[(cls, rule)]))
    round45 = [row for row in rows if row[0].startswith(".ufo/waves/round-45/")]
    print("round-45 findings=%d synthetic=%d"
          % (len(round45), sum(1 for row in round45 if row[3] == "SYNTHETIC")))
    print("wrote %s" % OUT)


if __name__ == "__main__":
    main()
